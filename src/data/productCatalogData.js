// Pre-indexed O(1) High-Performance Catalog Lookup Maps
const _groupsByDivisionAndSlug = new Map();
const _groupsBySlug = new Map();
const _categoriesByFullKey = new Map();
const _categoriesByGroupAndCat = new Map();
const _groupsByDivision = {
  manufacturer: [],
  supplier: []
};

// Build indexes once at module initialization
for (let i = 0; i < PRODUCT_GROUPS.length; i++) {
  const group = PRODUCT_GROUPS[i];
  const divSlug = (group.divisionSlug || '').toLowerCase().trim();
  const grpSlug = (group.slug || '').toLowerCase().trim();

  _groupsBySlug.set(grpSlug, group);
  _groupsByDivisionAndSlug.set(`${divSlug}/${grpSlug}`, group);

  if (_groupsByDivision[divSlug]) {
    _groupsByDivision[divSlug].push(group);
  }

  const categories = group.categories || [];
  for (let j = 0; j < categories.length; j++) {
    const cat = categories[j];
    const catSlug = (cat.slug || '').toLowerCase().trim();
    const item = {
      group,
      category: cat,
      ...cat,
      groupName: group.name,
      groupSlug: group.slug,
      division: group.division,
      divisionSlug: group.divisionSlug
    };
    _categoriesByFullKey.set(`${divSlug}/${grpSlug}/${catSlug}`, item);
    _categoriesByGroupAndCat.set(`${grpSlug}/${catSlug}`, item);
  }
}

export function getDivisionData(slug) {
  const clean = String(slug || '').toLowerCase().trim();
  const division = DIVISIONS[clean];
  if (!division) return null;
  const groups = _groupsByDivision[clean] || [];
  return { division, groups };
}

export function getAllProductGroups(divisionSlug = null) {
  if (!divisionSlug) return PRODUCT_GROUPS;
  const clean = String(divisionSlug).toLowerCase().trim();
  return _groupsByDivision[clean] || [];
}

export function getProductGroup(arg1, arg2) {
  if (!arg1) return null;
  if (!arg2) {
    const cleanGroup = String(arg1).toLowerCase().trim();
    return _groupsBySlug.get(cleanGroup) || null;
  }
  const cleanDiv = String(arg1).toLowerCase().trim();
  const cleanGroup = String(arg2).toLowerCase().trim();
  return _groupsByDivisionAndSlug.get(`${cleanDiv}/${cleanGroup}`) || _groupsBySlug.get(cleanGroup) || null;
}

export function getProductCategory(arg1, arg2, arg3) {
  if (!arg3) {
    const cleanGroup = String(arg1 || '').toLowerCase().trim();
    const cleanCat = String(arg2 || '').toLowerCase().trim();
    return _categoriesByGroupAndCat.get(`${cleanGroup}/${cleanCat}`) || null;
  }
  const cleanDiv = String(arg1 || '').toLowerCase().trim();
  const cleanGroup = String(arg2 || '').toLowerCase().trim();
  const cleanCat = String(arg3 || '').toLowerCase().trim();
  return _categoriesByFullKey.get(`${cleanDiv}/${cleanGroup}/${cleanCat}`) || _categoriesByGroupAndCat.get(`${cleanGroup}/${cleanCat}`) || null;
}

export function getRelatedProducts(arg1, arg2, limit = 4) {
  let groupSlug, categorySlug;
  if (typeof arg1 === 'object' && arg1 !== null) {
    groupSlug = arg1.groupSlug;
    categorySlug = arg1.slug;
    limit = typeof arg2 === 'number' ? arg2 : 4;
  } else {
    groupSlug = arg1;
    categorySlug = arg2;
  }

  const cleanGroup = String(groupSlug || '').toLowerCase().trim();
  const cleanCat = String(categorySlug || '').toLowerCase().trim();

  const sameGroup = [];
  const otherGroups = [];

  for (const group of PRODUCT_GROUPS) {
    for (const cat of group.categories || []) {
      if (group.slug === cleanGroup && cat.slug === cleanCat) {
        continue;
      }
      const item = {
        ...cat,
        groupName: group.name,
        groupSlug: group.slug,
        division: group.division,
        divisionSlug: group.divisionSlug
      };
      if (group.slug === cleanGroup) {
        sameGroup.push(item);
      } else {
        otherGroups.push(item);
      }
    }
  }

  return [...sameGroup, ...otherGroups].slice(0, limit);
}

export function searchCatalog(query = "") {
  const q = String(query).toLowerCase().trim();
  if (!q) return [];

  const results = [];
  for (const group of PRODUCT_GROUPS) {
    if (group.name.toLowerCase().includes(q) || group.shortDesc.toLowerCase().includes(q)) {
      results.push({
        type: "group",
        title: group.name,
        subtitle: group.tagline,
        url: `/products/${group.divisionSlug}/${group.slug}`,
        division: group.division,
        image: group.heroImage
      });
    }

    for (const cat of group.categories || []) {
      if (
        cat.name.toLowerCase().includes(q) ||
        cat.materialName.toLowerCase().includes(q) ||
        cat.grade.toLowerCase().includes(q) ||
        cat.shortDesc.toLowerCase().includes(q)
      ) {
        results.push({
          type: "product",
          title: cat.name,
          subtitle: `${group.name} • ${cat.grade}`,
          url: `/products/${group.divisionSlug}/${group.slug}/${cat.slug}`,
          division: group.division,
          image: cat.image
        });
      }
    }
  }

  return results.slice(0, 12);
}
